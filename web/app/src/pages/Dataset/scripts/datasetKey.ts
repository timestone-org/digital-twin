/**
 * @fileoverview 台账域里「标识」的字符集：列 key、库公式的调用标识与形参名
 * 共用同一条正则（后端都是 `ColumnKey`）。
 *
 * ⚠ 收在一处而不是每个表单各写一份：这条正则与后端逐字一致才有意义，
 * 抄第二份的那天两边就开始各改各的，而不一致的表现是「前端放行、后端 422」。
 */

/**
 * 与后端 `ColumnKey` 的 pattern 逐字一致。中文可用。
 * ⚠ `@` 必须禁掉：公式里 `@标识(` 是库公式调用的入口，标识里再混一个 `@`
 * 会让那道「源文本里没有 `@` 就一次库查询也不发」的快闸判错
 * （docs/DATASET_DESIGN.md §5.11）。
 */
export const KEY_PATTERN = /^[^\s@'"(),.:{}[\]]+$/

/** 不合法时说清楚哪些字符不许用；合法给空串。 */
export const KEY_CHARSET_HINT =
  '不能含空格与 @ . : , ( ) { } [ ] 引号，其余（含中文）都可以'
