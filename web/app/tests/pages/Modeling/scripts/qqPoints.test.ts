/** 一条实测阶梯：51 个分位上的实测残差值，加这份残差自己的偏均值与离散度。 */
interface Ladder {
  mean: number
  sd: number
  values: readonly number[]
}

/** 把一条阶梯折回后端给的那种逐项。Args: ladder。 */
function itemsOf(ladder: Ladder): Item[] {
  return Z.map((z, seat) => {
    const value = ladder.values[seat]
    if (value === undefined) throw new Error('阶梯上的分位点数不是 51 个')
    return {
      name: ((seat + 0.5) / SEATS).toFixed(3),
      value,
      expected: ladder.mean + ladder.sd * z,
      ratio: (seat + 0.5) / SEATS,
    }
  })
}

/** 一条阶梯下的那句结论。Args: ladder。 */
function ladderNote(ladder: Ladder): string {
  return noteOf(itemsOf(ladder))
}

