describe('行数够时五种残差仍各说各的', () => {
  interface Spread {
    phrase: string
    ladders: readonly Ladder[]
  }

  const SPREAD: readonly Spread[] = [
    { phrase: '接近正态', ladders: [NORMAL_3000_A, NORMAL_3000_B] },
    { phrase: '尾巴比正态厚', ladders: [HEAVY_3000_A, HEAVY_3000_B] },
    { phrase: '尾巴比正态薄', ladders: [LIGHT_3000_A, LIGHT_3000_B] },
    { phrase: '残差右偏', ladders: [RIGHT_3000_A, RIGHT_3000_B] },
    { phrase: '残差左偏', ladders: [LEFT_3000_A, LEFT_3000_B] },
  ]

  it('三千行的五种分布各点名自己那一种，两组种子都一样', () => {
    for (const one of SPREAD) {
      for (const ladder of one.ladders) {
        expect(ladderNote(ladder)).toContain(one.phrase)
      }
    }
  })

  it('行数够时把话说死：不带保留语气，也不退成量不出形状', () => {
    for (const one of SPREAD) {
      for (const ladder of one.ladders) {
        expect(ladderNote(ladder)).not.toContain('看起来')
        expect(ladderNote(ladder)).not.toContain('量不出形状')
      }
    }
  })

  it('五种分布说的是五句话，没有两种共用一句', () => {
    const notes = SPREAD.flatMap((one) => one.ladders.map(ladderNote))

    expect(notes).toHaveLength(10)
    expect(new Set(notes).size).toBe(5)
  })
})
